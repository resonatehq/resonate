# Generate AbstractCheck / ConcreteCheck: one forwarder per catalogue entry,
# so TLC names the failing guarantee. Regenerate after editing Invariants.tla.
import re

src = open('Invariants.tla').read()
trans_at = src.index('Stage 3 -- transition')
names = [(m.group(1), src.index(m.group(0)) > trans_at)
         for m in re.finditer(r'^([a-z][A-Za-z0-9_]*) ==$', src, re.M)]

for mod, base, inst in [
    ('AbstractCheck', 'Abstract', 'I == INSTANCE Invariants'),
    ('ConcreteCheck', 'Concrete', 'I == INSTANCE Invariants WITH objects <- Objects'),
]:
    with open(mod + '.tla', 'w') as f:
        pad = '-' * 20
        f.write(f"{pad} MODULE {mod} {pad}\n")
        f.write(f"(* GENERATED by mkcheck.py -- do not edit. *)\n")
        f.write(f"EXTENDS {base}\n\n{inst}\n\n")
        for n, is_trans in names:
            if is_trans:
                f.write(f"prop_{n} ==\n    [][I!{n}]_vars\n\n")
            else:
                f.write(f"inv_{n} ==\n    I!{n}\n\n")
        f.write("=" * 79 + "\n")

    basecfg = open(base + '.cfg').read()
    # keep everything up to the first INVARIANT/PROPERTY block
    kept = re.split(r'^(?:INVARIANT|PROPERTY)\b', basecfg, flags=re.M)[0]
    with open(mod + '.cfg', 'w') as f:
        f.write(kept.rstrip() + '\n\nINVARIANT\n')
        for n, is_trans in names:
            if not is_trans:
                f.write(f"    inv_{n}\n")
        f.write('\nPROPERTY\n')
        for n, is_trans in names:
            if is_trans:
                f.write(f"    prop_{n}\n")
        if 'CHECK_DEADLOCK' in basecfg:
            f.write('\nCHECK_DEADLOCK FALSE\n')
print("generated")
